function detectLang() {
  const fromQuery = new URLSearchParams(location.search).get("lang");
  if (fromQuery === "en" || fromQuery === "ko") return fromQuery;
  let saved = null;
  try { saved = localStorage.getItem(LANG_STORAGE_KEY); } catch (_) { /* 저장소를 못 쓰는 환경 */ }
  if (saved === "en" || saved === "ko") return saved;
  return (navigator.language || "").toLowerCase().startsWith("ko") ? "ko" : "en";  // 첫 방문만
}

let LANG = detectLang();

function tr(id, params) {
  let s = (MESSAGES[LANG] && MESSAGES[LANG][id]) || MESSAGES.en[id] || id;
  for (const [k, v] of Object.entries(params || {})) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// HTML 의 data-i18n(텍스트)·data-i18n-placeholder·data-i18n-aria 를 현재 언어로 채운다
function applyStaticTexts() {
  document.documentElement.lang = LANG;
  document.title = tr("page.title");
  for (const n of document.querySelectorAll("[data-i18n]")) n.textContent = tr(n.dataset.i18n);
  for (const n of document.querySelectorAll("[data-i18n-placeholder]")) n.placeholder = tr(n.dataset.i18nPlaceholder);
  for (const n of document.querySelectorAll("[data-i18n-aria]")) n.setAttribute("aria-label", tr(n.dataset.i18nAria));
  const picker = document.getElementById("lang-select");
  if (picker) picker.value = LANG;
}

function setLang(next) {
  if (next !== "en" && next !== "ko") return;
  LANG = next;
  try { localStorage.setItem(LANG_STORAGE_KEY, next); } catch (_) { /* 저장 못 해도 이번 화면은 바뀐다 */ }
  applyStaticTexts();
}
